package dev.jonalakas.bridgepad.output.hid

object GamepadHidDescriptor {
    const val REPORT_ID = 1

    val bytes = byteArrayOf(
        0x05, 0x01,       // Usage Page (Generic Desktop)
        0x09, 0x05,       // Usage (Game Pad)
        0xA1.toByte(), 0x01, // Collection (Application)
        0x85.toByte(), REPORT_ID.toByte(),
        0x05, 0x09,       // Usage Page (Button)
        0x19, 0x01,
        0x29, 0x10,
        0x15, 0x00,
        0x25, 0x01,
        0x75, 0x01,
        0x95.toByte(), 0x10,
        0x81.toByte(), 0x02,
        0x05, 0x01,
        0x09, 0x39,       // Hat switch
        0x15, 0x00,
        0x25, 0x07,
        0x35, 0x00,
        0x46, 0x3B, 0x01,
        0x65, 0x14,
        0x75, 0x04,
        0x95.toByte(), 0x01,
        0x81.toByte(), 0x42,
        0x65, 0x00,
        0x75, 0x04,
        0x95.toByte(), 0x01,
        0x81.toByte(), 0x03,
        0x09, 0x30,       // X
        0x09, 0x31,       // Y
        0x09, 0x33,       // Rx
        0x09, 0x34,       // Ry
        0x15, 0x81.toByte(),
        0x25, 0x7F,
        0x75, 0x08,
        0x95.toByte(), 0x04,
        0x81.toByte(), 0x02,
        0x09, 0x32,       // Z
        0x09, 0x35,       // Rz
        0x15, 0x00,
        0x26, 0xFF.toByte(), 0x00,
        0x75, 0x08,
        0x95.toByte(), 0x02,
        0x81.toByte(), 0x02,
        0xC0.toByte(),
    )

    fun neutralReport(): ByteArray = byteArrayOf(0, 0, 8, 0, 0, 0, 0, 0, 0)

    fun southButtonReport(pressed: Boolean): ByteArray = neutralReport().also {
        if (pressed) it[0] = 0x01
    }
}
