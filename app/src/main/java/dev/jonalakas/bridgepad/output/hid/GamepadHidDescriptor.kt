package dev.jonalakas.bridgepad.output.hid

import dev.jonalakas.bridgepad.core.gamepad.VirtualGamepadState
import dev.jonalakas.bridgepad.core.output.HidReportEncoder

object GamepadHidDescriptor {
    const val REPORT_ID = 1
    const val MOUSE_REPORT_ID = 2

    val bytes = byteArrayOf(
        0x05, 0x01,       // Usage Page (Generic Desktop)
        0x09, 0x05,       // Usage (Game Pad)
        0xA1.toByte(), 0x01, // Collection (Application)
        0x85.toByte(), REPORT_ID.toByte(),
        0x05, 0x09,       // Usage Page (Button)
        0x19, 0x01,
        0x29, 0x10,
        0x15, 0x00,
        0x25, 0x01,
        0x75, 0x01,
        0x95.toByte(), 0x10,
        0x81.toByte(), 0x02,
        0x05, 0x01,
        0x09, 0x39,       // Hat switch
        0x15, 0x00,
        0x25, 0x07,
        0x35, 0x00,
        0x46, 0x3B, 0x01,
        0x65, 0x14,
        0x75, 0x04,
        0x95.toByte(), 0x01,
        0x81.toByte(), 0x42,
        0x65, 0x00,
        0x75, 0x04,
        0x95.toByte(), 0x01,
        0x81.toByte(), 0x03,
        0x09, 0x30,       // X
        0x09, 0x31,       // Y
        0x09, 0x33,       // Rx
        0x09, 0x34,       // Ry
        0x15, 0x81.toByte(),
        0x25, 0x7F,
        0x75, 0x08,
        0x95.toByte(), 0x04,
        0x81.toByte(), 0x02,
        0x09, 0x32,       // Z
        0x09, 0x35,       // Rz
        0x15, 0x00,
        0x26, 0xFF.toByte(), 0x00,
        0x75, 0x08,
        0x95.toByte(), 0x02,
        0x81.toByte(), 0x02,
        0xC0.toByte(),

        0x05, 0x01,       // Usage Page (Generic Desktop)
        0x09, 0x02,       // Usage (Mouse)
        0xA1.toByte(), 0x01, // Collection (Application)
        0x85.toByte(), MOUSE_REPORT_ID.toByte(),
        0x09, 0x01,       // Usage (Pointer)
        0xA1.toByte(), 0x00, // Collection (Physical)
        0x05, 0x09,       // Usage Page (Button)
        0x19, 0x01,
        0x29, 0x03,
        0x15, 0x00,
        0x25, 0x01,
        0x75, 0x01,
        0x95.toByte(), 0x03,
        0x81.toByte(), 0x02,
        0x75, 0x05,
        0x95.toByte(), 0x01,
        0x81.toByte(), 0x03,
        0x05, 0x01,
        0x09, 0x30,       // Usage (X)
        0x09, 0x31,       // Usage (Y)
        0x15, 0x81.toByte(),
        0x25, 0x7F,
        0x75, 0x08,
        0x95.toByte(), 0x02,
        0x81.toByte(), 0x06, // Data, Variable, Relative
        0xC0.toByte(),
        0xC0.toByte(),
    )

    fun neutralReport(): ByteArray = HidReportEncoder.encode(VirtualGamepadState())

    fun mouseReport(buttons: Int, deltaX: Int, deltaY: Int): ByteArray = byteArrayOf(
        (buttons and 0x07).toByte(),
        deltaX.coerceIn(-127, 127).toByte(),
        deltaY.coerceIn(-127, 127).toByte(),
    )
}
